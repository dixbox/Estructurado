public class BubleTres {
    public static void main(String[] args) {
        int i = 1;//Contador
        //Inicia ciclo
        do {
            System.out.println("El valor de i es: " + i);
            i++;//Incremento en 1 en cada vuelta de ciclo
        } while (i <= 7);//Evalua la instruccion de paro para las iteraciones
    }
}
